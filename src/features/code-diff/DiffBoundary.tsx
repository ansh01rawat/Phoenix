import { Component, type ReactNode } from 'react'

/** Optional editor failure must not take down the workspace or its readable comparison. */
export class DiffBoundary extends Component<
  { children: ReactNode; fallback: ReactNode },
  { failed: boolean }
> {
  state = { failed: false }
  static getDerivedStateFromError() {
    return { failed: true }
  }
  render() {
    return this.state.failed ? this.props.fallback : this.props.children
  }
}
